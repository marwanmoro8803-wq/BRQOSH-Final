namespace Brqosh.Domain.Inventory;

/// <summary>
/// (CEEF-230 · ط1-٣) <b>نمطُ تتبّع الصنف.</b>
///
/// <para>الصنفُ إمّا يُتتبَّع بالكمّية وحدها، أو <b>بالدفعة</b> (لبنٌ من تشغيلةٍ لها صلاحية،
/// دواءٌ من لوطٍ له تاريخُ انتهاء)، أو <b>بالرقم التسلسليّ</b> (جهازٌ بعينه، مركبةٌ بعينها).</para>
///
/// <para><b>والفرقُ بين الأخيرين ليس تسميةً</b>: الدفعةُ كمّيةٌ من وحداتٍ متماثلة يجمعها
/// رقمٌ وتاريخُ صلاحية، والرقمُ التسلسليّ <b>وحدةٌ واحدة</b> لا تقبل الكسر ولا التكرار.
/// فالسريالُ دفعةٌ كمّيتُها واحدٌ أبداً — وهذا ما يفرضه النطاق لا الاصطلاح.</para>
/// </summary>
public enum InventoryTracking
{
    /// <summary>بالكمّية وحدها — وهو الأصل، ولا يتغيّر سلوكُ الأصناف القائمة.</summary>
    None = 0,

    /// <summary>بالدفعة: رقمُ دفعةٍ وتاريخُ صلاحيةٍ اختياريّ، والكمّيةُ قابلةٌ للتجزئة.</summary>
    Batch = 1,

    /// <summary>بالرقم التسلسليّ: وحدةٌ واحدةٌ لكلّ رقم، ولا يتكرّر الرقمُ في المنشأة.</summary>
    Serial = 2,
}
