namespace Brqosh.Domain.Accounting;

/// <summary>
/// (CEEF-229 · م2-٢) <b>سعرُ الوحدة لا يتجاوز خانتَي الهللة.</b>
///
/// <para><b>العطل الذي أغلقه هذا الحارس — وهو عطلُ إنتاجٍ لا نظرية:</b> عمودُ سعر الوحدة في
/// كلّ جداول السطور <c>numeric(18,2)</c>، ولم يكن على خاناته حارسٌ إطلاقاً. فكرتونٌ فيه
/// ٢٤ حبّة بـ ٤٥.٠٠ ريال يُدخَل بسعر حبّةٍ <c>1.875</c>:</para>
///
/// <list type="bullet">
/// <item>الإجماليّ يُحسب <b>في الذاكرة</b> من <c>1.875</c> ⟵ ٤٥.٠٠ ويُخزَّن صحيحاً.</item>
/// <item>والسطرُ يُخزَّن في عمودٍ بخانتين ⟵ <c>1.88</c> على PostgreSQL، و<c>1.875</c> على SQLite.</item>
/// <item>فعند إعادة القراءة — وهي ما يفعله الطبعُ وإعادةُ احتساب الإجماليات عند كلّ إقلاع —
/// يصير مجموعُ السطور <b>45.12</b> والإجماليُّ المخزَّن <b>45.00</b>.</item>
/// </list>
///
/// <para>أي أنّ <b>الفاتورة الضريبية المطبوعة لا تجمع نفسها</b>: عمودُ الوعاء لا يساوي
/// الإجماليَّ المطبوع تحته — وهذا ما تسأل عنه هيئة الزكاة. <b>وعلى الإنتاج وحده</b>: على
/// SQLite — حيث تعمل الاختبارات كلُّها — الرقمان متطابقان، فلم يكن للعطل أثرٌ يُرى.</para>
///
/// <para><b>ولماذا رفضٌ لا تقريبٌ صامت:</b> التقريب يغيّر إجماليَّ الفاتورة عمّا كتبه صاحبُها
/// دون أن يخبره. والرفضُ يُبقي القرار عنده: إمّا يُقرّب السعر بنفسه، أو يُدخل الكرتون سطراً
/// واحداً بـ ٤٥.٠٠ — وهو التمثيل الصحيح لما باعه أصلاً. وهذا هو مسلكُ
/// <see cref="JournalEntry"/> نفسه مع مبالغ السطور.</para>
/// </summary>
public static class DocumentLineScale
{
    /// <summary>يرمي إن تجاوز سعرُ الوحدة خانتَي الهللة — فالعمود لا يتّسع لأكثر.</summary>
    public static void EnsureUnitPriceHalala(decimal unitPrice)
    {
        if (unitPrice != decimal.Round(unitPrice, 2))
            throw new AccountingException(
                $"سعر الوحدة {unitPrice} يتجاوز خانتَي الهللة. قرِّب السعر، "
                + "أو أدخِل العبوة سطراً واحداً بسعرها الكامل.");
    }
}
