namespace Brqosh.Domain.Shared;

/// <summary>
/// (م-٢ · ن-٣٠) <b><c>char.IsDigit</c> يعدّ الأرقامَ العربية-الهندية أرقاماً — فيخرج «٣١٢٣…»
/// في <c>cbc:CompanyID</c> لدى الهيئة.</b>
///
/// <para><c>char.IsDigit('٣')</c> يُعيد <c>true</c>: الدالّةُ تسأل عن <b>فئة يونيكود</b>
/// (<c>DecimalDigitNumber</c>)، لا عن المحارف <c>'0'</c>…<c>'9'</c>. والأرقامُ العربية-الهندية
/// (U+0660…U+0669) والفارسيّة (U+06F0…U+06F9) وعشراتُ المجموعات غيرُها كلُّها في تلك الفئة.</para>
///
/// <para><b>ولماذا هذا S0:</b> مستخدمٌ بلوحة مفاتيح عربية يكتب رقمَه الضريبيّ «٣١٢٣…»
/// فيجتاز التحقّق — <b>ويُكتب كما هو في XML الفاتورة</b>. والهيئةُ تنتظر خمسةَ عشرَ محرفاً
/// لاتينيّاً؛ فإمّا يُرفض المستند، أو — وهو الأسوأ — يُقبل برقمٍ لا يطابق سجلَّ المنشأة.
/// وفي الحالتين <b>لا يعلم المستخدمُ أنّ ما كتبه ليس ما أُرسل</b>.</para>
///
/// <para><b>والأثرُ أوسعُ من الرقم الضريبيّ:</b> النمطُ نفسُه يحرس أكوادَ الحسابات وأرقامَ
/// المباني والرموزَ البريديّة — وكلُّها تخرج في مستنداتٍ أو تُطابَق نصّياً.</para>
///
/// <para><b>ولا تطبيعَ هنا عمداً.</b> تحويلُ «٣» إلى «3» صامتاً يجعل المُدخلَ يختلف عن
/// المُخرَج بلا علمِ كاتبه — وهو عطلُ «الرقمُ الذي أراه ليس الذي أُرسل» بصورةٍ أخرى.
/// فالرفضُ المُسمّى أصدق: يعرف المستخدمُ فوراً ما المطلوب.</para>
/// </summary>
public static class AsciiDigits
{
    /// <summary>محرفٌ لاتينيٌّ من <c>'0'</c> إلى <c>'9'</c> — لا فئةُ يونيكود.</summary>
    public static bool Is(char c) => c is >= '0' and <= '9';

    /// <summary>هل السلسلةُ كلُّها أرقامٌ لاتينيّة؟ (‏الفارغةُ ليست كذلك.)</summary>
    public static bool All(string? value) =>
        !string.IsNullOrEmpty(value) && value.All(Is);

    /// <summary>هل السلسلةُ أرقامٌ لاتينيّةٌ بطولٍ محدَّد؟</summary>
    public static bool AllOfLength(string? value, int length) =>
        value is not null && value.Length == length && value.All(Is);
}
