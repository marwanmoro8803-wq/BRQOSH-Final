using System.Text;
using System.Text.Json;

namespace PromptAuditEngine;

internal static class AuditReportWriter
{
    public static void Write(AuditEngineResult result, string outDir)
    {
        Directory.CreateDirectory(outDir);
        var md = Path.Combine(outDir, "latest.md");
        var json = Path.Combine(outDir, "latest.json");
        File.WriteAllText(md, BuildMarkdown(result), Encoding.UTF8);
        File.WriteAllText(json, JsonSerializer.Serialize(result, new JsonSerializerOptions { WriteIndented = true }), Encoding.UTF8);
    }

    private static string BuildMarkdown(AuditEngineResult r)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Prompt Audit Engine — Universal Report");
        sb.AppendLine();
        sb.AppendLine($"| Field | Value |");
        sb.AppendLine($"|-------|-------|");
        sb.AppendLine($"| **Generated** | {r.GeneratedUtc:yyyy-MM-dd HH:mm:ss} UTC |");
        sb.AppendLine($"| **Repo** | `{r.RepoRoot}` |");
        sb.AppendLine($"| **Strength** | {r.StrengthScore}/100 |");
        sb.AppendLine($"| **Overall** | {(r.OverallPass ? "✅ PASS" : "🟡 PARTIAL")} |");
        sb.AppendLine($"| **Summary** | {r.Summary} |");
        if (!string.IsNullOrWhiteSpace(r.TargetAppPath))
            sb.AppendLine($"| **Target app (stub)** | `{r.TargetAppPath}` |");
        sb.AppendLine();

        sb.AppendLine("## Stacks detected");
        foreach (var s in r.Stacks)
            sb.AppendLine($"- **{s.Label}** (`{s.Id}`) — `{s.ManifestPath ?? "n/a"}`");
        sb.AppendLine();

        sb.AppendLine("## Verifications");
        if (r.Verifications.Count == 0)
            sb.AppendLine("_No build commands run (skip-build or skills-only)._");
        else
            foreach (var v in r.Verifications)
                sb.AppendLine($"- [{v.StackId}] `{(v.Passed ? "PASS" : "FAIL")}` exit={v.ExitCode} — `{v.Command}`");
        sb.AppendLine();

        sb.AppendLine("## Linkage");
        sb.AppendLine($"Score: **{r.Linkage.Score}/100**");
        foreach (var f in r.Linkage.Findings)
            sb.AppendLine($"- {f.Code}: {(f.Pass ? "✓" : "✗")} {f.Detail}");
        sb.AppendLine();

        sb.AppendLine("## Workflow / governance");
        sb.AppendLine($"Score: **{r.Workflow.Score}/100**");
        sb.AppendLine($"- PROJECT.yaml: {r.Workflow.ProjectYaml}");
        sb.AppendLine($"- ShuraCouncil: {r.Workflow.ShuraTool}");
        sb.AppendLine($"- PromptAuditEngine: {r.Workflow.AuditEngineSelf}");
        sb.AppendLine($"- Skills complete: {r.Workflow.SkillsComplete}");
        sb.AppendLine($"- P2 skills: {r.Workflow.P2SkillsComplete}");
        sb.AppendLine($"- P3 launcher law: {r.Workflow.P3SkillsComplete}");
        sb.AppendLine($"- prompt-source-law: {r.Workflow.PromptLaw}");
        sb.AppendLine($"- leak index: {r.Workflow.LeakIndex}");
        sb.AppendLine($"- CI/ops scripts: {r.Workflow.CiWorkflow}");
        sb.AppendLine();
        sb.AppendLine("---");
        sb.AppendLine("*Generated by `PromptAuditEngine` — skills-governed harness · not cognitive-qa Python.*");
        return sb.ToString();
    }
}
